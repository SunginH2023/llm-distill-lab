"""Run all experiments in order and rebuild results/RESULTS.md.

    python experiments/run_all.py      (or: make all)

Everything is deterministic in the same numpy/BLAS environment — the same commit produces the same numbers
no matter how many times it is run. Last-digit float differences can appear across environments; the
rounded numbers in the reports are unchanged.
"""

from __future__ import annotations

import pathlib as _p
import sys as _s
_s.path.insert(0, str(_p.Path(__file__).resolve().parent.parent))
import lab as _lab  # noqa: F401  (pin BLAS threads before importing numpy)

import importlib
import io
import time
from contextlib import redirect_stdout

from lab.report import RESULTS

ORDER = [
    "e1_consensus_gate",
    "e2_circular_eval",
    "e3_soft_labels",
    "e4_call_budget",
    "e5_cardinality",
]

HEADER = """# Experiment results (auto-generated)

Regenerated by `python experiments/run_all.py`. Do not edit by hand.
Every number comes from synthetic data with fixed seeds — not a single line of production data is included.

"""


def main() -> None:
    RESULTS.mkdir(exist_ok=True)
    parts, t_start = [HEADER], time.time()
    for name in ORDER:
        mod = importlib.import_module(f"experiments.{name}")
        t0 = time.time()
        buf = io.StringIO()
        with redirect_stdout(buf):          # each experiment also prints its own md to stdout
            mod.main()
        print(f"[{name}] {time.time() - t0:.1f}s")
        parts.append((RESULTS / f"{name}.md").read_text(encoding="utf-8"))

    (RESULTS / "RESULTS.md").write_text("\n\n---\n\n".join(parts), encoding="utf-8")
    print(f"→ results/RESULTS.md  (total {time.time() - t_start:.1f}s)")


if __name__ == "__main__":
    main()
